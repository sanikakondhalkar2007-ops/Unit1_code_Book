#include <iostream>              // Includes the iostream library for input and output

using namespace std;             // Allows us to use cout and endl without std::

int main() {                     // Main function where program execution starts

    int roll = 101;              // Declares an integer variable roll and stores 101

    char grade = 'A';            // Declares a character variable grade and stores 'A'

    float fee = 12500.50;        // Declares a float variable fee and stores a decimal value

    cout << "Roll No: " << roll << endl;    // Displays the student's roll number

    cout << "Grade: " << grade << endl;     // Displays the student's grade

    cout << "Fee: " << fee << endl;         // Displays the student's fee amount

    return 0;                     // Ends the program successfully
}